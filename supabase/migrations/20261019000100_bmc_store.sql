-- BMC finals catalog and immutable, server-priced order snapshots.
create table public.products (
  id bigint primary key generated by default as identity,
  name text not null check (length(btrim(name)) between 1 and 200),
  price numeric(12, 2) not null check (price > 0),
  image_url text
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete restrict,
  product_id bigint not null references public.products(id) on delete restrict,
  product_name text not null check (length(btrim(product_name)) between 1 and 200),
  amount numeric(12, 2) not null check (amount > 0),
  currency text not null default 'PHP' check (currency = 'PHP'),
  external_id text not null unique check (length(external_id) between 1 and 200),
  xendit_invoice_id text unique check (length(xendit_invoice_id) between 1 and 200),
  invoice_url text,
  status text not null default 'PENDING' check (status in ('PENDING', 'PAID', 'EXPIRED', 'FAILED')),
  created_at timestamptz not null default now(),
  paid_at timestamptz,
  constraint orders_paid_at_consistency check ((status = 'PAID') = (paid_at is not null))
);

create index orders_user_created_idx on public.orders(user_id, created_at desc);

-- Reserve an order from the trusted catalog. Client-supplied prices/names are never accepted.
create function public.create_checkout_order(
  p_user_id uuid,
  p_product_id bigint,
  p_external_id text
) returns setof public.orders
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_order public.orders%rowtype;
begin
  if p_user_id is null or p_product_id is null
    or p_external_id is null or length(p_external_id) not between 1 and 200 then
    raise exception 'INVALID_CHECKOUT_ORDER' using errcode = '22023';
  end if;

  insert into public.orders (user_id, product_id, product_name, amount, currency, external_id)
  select p_user_id, p.id, p.name, p.price, 'PHP', p_external_id
  from public.products as p
  where p.id = p_product_id
  returning * into v_order;

  if not found then
    raise exception 'PRODUCT_NOT_FOUND' using errcode = 'P0002';
  end if;
  return next v_order;
end;
$$;

-- Apply Xendit callbacks under a row lock; mismatches and stale events cannot mutate an order.
create function public.apply_xendit_invoice_event(
  p_external_id text,
  p_invoice_id text,
  p_status text,
  p_amount numeric,
  p_currency text
) returns text
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_order public.orders%rowtype;
begin
  if p_status is null or p_status not in ('PAID', 'EXPIRED') then
    raise exception 'INVALID_INVOICE_EVENT' using errcode = '22023';
  end if;

  select o.* into v_order
  from public.orders as o
  where o.external_id = p_external_id
  for update;

  if not found then return 'not_found'; end if;
  if v_order.xendit_invoice_id is null or v_order.xendit_invoice_id <> p_invoice_id then
    return 'invoice_mismatch';
  end if;
  if p_amount is distinct from v_order.amount then return 'amount_mismatch'; end if;
  if p_currency is distinct from v_order.currency then return 'currency_mismatch'; end if;

  if p_status = 'PAID' then
    if v_order.status = 'PAID' then return 'already_applied'; end if;
    update public.orders
      set status = 'PAID', paid_at = coalesce(paid_at, pg_catalog.now())
      where id = v_order.id;
    return 'updated';
  end if;

  if v_order.status <> 'PENDING' then return 'already_applied'; end if;
  update public.orders set status = 'EXPIRED' where id = v_order.id;
  return 'updated';
end;
$$;

revoke all on function public.create_checkout_order(uuid, bigint, text) from public, anon, authenticated;
grant execute on function public.create_checkout_order(uuid, bigint, text) to service_role;
revoke all on function public.apply_xendit_invoice_event(text, text, text, numeric, text) from public, anon, authenticated;
grant execute on function public.apply_xendit_invoice_event(text, text, text, numeric, text) to service_role;

alter table public.products enable row level security;
alter table public.orders enable row level security;

revoke all on table public.products, public.orders from public, anon, authenticated;
revoke all on sequence public.products_id_seq from public, anon, authenticated;
grant select on public.products to anon, authenticated;
grant select on public.orders to authenticated;
grant select, insert, update, delete on public.products, public.orders to service_role;
grant usage, select on sequence public.products_id_seq to service_role;

create policy catalog_public_read on public.products
  for select to anon, authenticated using (true);
create policy orders_owner_read on public.orders
  for select to authenticated using ((select auth.uid()) = user_id);
-- No client mutation policies, and no client write grants.
